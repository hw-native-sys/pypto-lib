        position_ids,
        kv_seq_lens,
        block_table,
        hca_cmp_block_table,
        csa_cmp_block_table,
        idx_block_table,
        hca_compress_state_block_table,
        csa_compress_state_block_table,
        csa_inner_compress_state_block_table,
        block_counts,
        ori_slot_mapping,
        swa_slot_mapping,
        swa_indices,
        swa_lens,
