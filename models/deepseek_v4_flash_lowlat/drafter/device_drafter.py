import pypto.language as pl

import pypto.language.distributed as pld

from .device_metadata import select_drafter_metadata

from .device_metadata import BANK_COUNT

from .dspark_drafter import (
    ATTENTION_WINDOW_ROWS,
    AUX_PAD,
    BLOCK_SIZE,
    D,
    DSPARK_CP_SIZE,
    DSPARK_DRAFT_LAYERS,
    H,
    HC_DIM,
    HC_MULT,
    HEAD_DIM,
    IDX_PAD,
    LOCAL_O_GROUPS,
    MAIN_IN,
    MIX_HC,
    MOE_INTER,
    N_EXPERTS_GLOBAL,
    N_LOCAL,
    N_RANKS,
    N_ROUTES,
    ORI_BLOCK_NUM,
    O_GROUP_IN,
    O_LORA,
    O_WINDOW_ROWS,
    PREFILL_GROUP_CAP,
    Q_LORA,
    RECV_MAX,
    T,
    TOPK,
    TP_SIZE,
    VOCAB,
    dspark_drafter,
)


def _device_dspark_drafter(
    target_hidden: pl.Tensor[[128, 12288], pl.BF16],
    main_proj_weight: pl.Tensor[[D, MAIN_IN], pl.BF16],
    main_norm_weight: pl.Tensor[[D], pl.BF16],
    request_state: pl.Tensor[[4], pl.INT64],
    last_sampled: pl.Out[pl.Tensor[[1], pl.INT64]],
    embedding_weight: pl.Tensor[[VOCAB, D], pl.BF16],
    context_group_position_ids_bank: pl.Tensor[[BANK_COUNT, 512], pl.INT32],
    context_group_slot_mapping_bank: pl.Tensor[[BANK_COUNT, 3, 512], pl.INT64],
    block_tables: pl.Tensor[[3, 1, 32768], pl.INT32],
    query_group_position_ids_bank: pl.Tensor[[BANK_COUNT, 80], pl.INT32],
    query_group_slot_mapping_bank: pl.Tensor[[BANK_COUNT, 3, 80], pl.INT64],
    context_group_freqs_cos_bank: pl.Tensor[[BANK_COUNT, 512, 64], pl.BF16],
    context_group_freqs_sin_bank: pl.Tensor[[BANK_COUNT, 512, 64], pl.BF16],
    query_freqs_cos_bank: pl.Tensor[[BANK_COUNT, 20, 64], pl.BF16],
    query_freqs_sin_bank: pl.Tensor[[BANK_COUNT, 20, 64], pl.BF16],
    query_group_freqs_cos_bank: pl.Tensor[[BANK_COUNT, 80, 64], pl.BF16],
    query_group_freqs_sin_bank: pl.Tensor[[BANK_COUNT, 80, 64], pl.BF16],
    hc_attn_fn: pl.Tensor[[DSPARK_DRAFT_LAYERS * MIX_HC, HC_DIM], pl.FP32],
    hc_attn_scale: pl.Tensor[[DSPARK_DRAFT_LAYERS * 3], pl.FP32],
    hc_attn_base: pl.Tensor[[DSPARK_DRAFT_LAYERS * MIX_HC], pl.FP32],
    attn_norm_w: pl.Tensor[[DSPARK_DRAFT_LAYERS * D], pl.BF16],
    wq_a: pl.Tensor[[DSPARK_DRAFT_LAYERS, D, Q_LORA], pl.BF16, pl.NZ],
    wq_b: pl.Tensor[[DSPARK_DRAFT_LAYERS, Q_LORA, H * HEAD_DIM], pl.INT8, pl.NZ],
    wq_b_scale: pl.Tensor[[DSPARK_DRAFT_LAYERS * H * HEAD_DIM], pl.FP32],
    wkv: pl.Tensor[[DSPARK_DRAFT_LAYERS * D, HEAD_DIM], pl.BF16],
    gamma_cq: pl.Tensor[[DSPARK_DRAFT_LAYERS * Q_LORA], pl.BF16],
    gamma_ckv: pl.Tensor[[DSPARK_DRAFT_LAYERS * HEAD_DIM], pl.BF16],
    kv_caches: pl.InOut[pl.Tensor[[DSPARK_DRAFT_LAYERS, ORI_BLOCK_NUM, BLOCK_SIZE, 1, HEAD_DIM], pl.BF16]],
    attn_sink: pl.Tensor[[DSPARK_DRAFT_LAYERS * H], pl.FP32],
    wo_a: pl.Tensor[[DSPARK_DRAFT_LAYERS * LOCAL_O_GROUPS, O_LORA, O_GROUP_IN], pl.BF16, pl.NZ],
    wo_b: pl.Tensor[[DSPARK_DRAFT_LAYERS * LOCAL_O_GROUPS, D, O_LORA], pl.INT8, pl.NZ],
    wo_b_scale: pl.Tensor[[DSPARK_DRAFT_LAYERS * D], pl.FP32],
    hc_ffn_fn: pl.Tensor[[DSPARK_DRAFT_LAYERS * MIX_HC, HC_DIM], pl.FP32],
    hc_ffn_scale: pl.Tensor[[DSPARK_DRAFT_LAYERS * 3], pl.FP32],
    hc_ffn_base: pl.Tensor[[DSPARK_DRAFT_LAYERS * MIX_HC], pl.FP32],
    ffn_norm_w: pl.Tensor[[DSPARK_DRAFT_LAYERS * D], pl.BF16],
    gate_w: pl.Tensor[[DSPARK_DRAFT_LAYERS * N_EXPERTS_GLOBAL, D], pl.FP32],
    gate_bias: pl.Tensor[[DSPARK_DRAFT_LAYERS * N_EXPERTS_GLOBAL], pl.FP32],
    tid2eid: pl.Tensor[[DSPARK_DRAFT_LAYERS * VOCAB, TOPK], pl.INT32],
    routed_w1: pl.Tensor[[DSPARK_DRAFT_LAYERS * N_LOCAL, MOE_INTER, D], pl.INT8, pl.NZ],
    routed_w1_scale: pl.Tensor[[DSPARK_DRAFT_LAYERS * N_LOCAL, MOE_INTER], pl.FP32],
    routed_w3: pl.Tensor[[DSPARK_DRAFT_LAYERS * N_LOCAL, MOE_INTER, D], pl.INT8, pl.NZ],
    routed_w3_scale: pl.Tensor[[DSPARK_DRAFT_LAYERS * N_LOCAL, MOE_INTER], pl.FP32],
    routed_w2: pl.Tensor[[DSPARK_DRAFT_LAYERS * N_LOCAL, D, MOE_INTER], pl.INT8, pl.NZ],
    routed_w2_scale: pl.Tensor[[DSPARK_DRAFT_LAYERS * N_LOCAL, D], pl.FP32],
    shared_w1: pl.Tensor[[DSPARK_DRAFT_LAYERS, MOE_INTER, D], pl.INT8, pl.NZ],
    shared_w1_scale: pl.Tensor[[DSPARK_DRAFT_LAYERS * MOE_INTER], pl.FP32],
    shared_w3: pl.Tensor[[DSPARK_DRAFT_LAYERS, MOE_INTER, D], pl.INT8, pl.NZ],
    shared_w3_scale: pl.Tensor[[DSPARK_DRAFT_LAYERS * MOE_INTER], pl.FP32],
    shared_w2: pl.Tensor[[DSPARK_DRAFT_LAYERS, D, MOE_INTER], pl.INT8, pl.NZ],
    shared_w2_scale: pl.Tensor[[DSPARK_DRAFT_LAYERS * D], pl.FP32],
    hc_head_fn: pl.Tensor[[HC_MULT, HC_DIM], pl.FP32],
    hc_head_scale: pl.Tensor[[1], pl.FP32],
    hc_head_base: pl.Tensor[[HC_MULT], pl.FP32],
    initial_hidden: pl.Out[pl.Tensor[[T, HC_MULT, D], pl.FP32]],
    intermediate_hidden: pl.Out[pl.Tensor[[DSPARK_DRAFT_LAYERS, T, HC_MULT, D], pl.FP32]],
    head_hidden: pl.Out[pl.Tensor[[1, 5, 4096], pl.BF16]],
    hidden_gather_window: pld.DistributedTensor[[PREFILL_GROUP_CAP, D], pl.BF16],
    hidden_gather_signal: pld.DistributedTensor[[DSPARK_CP_SIZE, 1], pl.INT32],
    attention_window: pld.DistributedTensor[[ATTENTION_WINDOW_ROWS, O_GROUP_IN], pl.BF16],
    attention_signal: pld.DistributedTensor[[TP_SIZE, 1], pl.INT32],
    o_window: pld.DistributedTensor[[O_WINDOW_ROWS, D], pl.BF16],
    o_signal: pld.DistributedTensor[[TP_SIZE, 1], pl.INT32],
    recv_meta: pld.DistributedTensor[[N_RANKS, N_LOCAL], pl.INT32],
    recv_x: pld.DistributedTensor[[N_LOCAL * RECV_MAX, D], pl.INT8],
    recv_aux: pld.DistributedTensor[[N_LOCAL * RECV_MAX, AUX_PAD], pl.FP32],
    recv_route: pld.DistributedTensor[[N_LOCAL * RECV_MAX, IDX_PAD], pl.INT32],
    arrived: pld.DistributedTensor[[N_RANKS, 1], pl.INT32],
    data_arrived: pld.DistributedTensor[[N_RANKS, 1], pl.INT32],
    routed_y_buf: pld.DistributedTensor[[N_ROUTES, D], pl.BF16],
    combine_arrived: pld.DistributedTensor[[N_RANKS, 1], pl.INT32],
    group_base: pl.Scalar[pl.INT32],
    dsa_cp_rank: pl.Scalar[pl.INT32],
    my_rank: pl.Scalar[pl.INT32],
    prior_cycle_gate: pl.Scalar[pl.TASK_ID],
):
    """Select metadata from committed device state and run the unchanged cap4 Drafter."""
    num_sampled = pl.create_tensor([1], dtype=pl.INT32)
    next_prefill_tokens = pl.create_tensor([1], dtype=pl.INT64)
    anchor_positions = pl.create_tensor([1], dtype=pl.INT32)
    context_group_position_ids = pl.create_tensor([512], dtype=pl.INT32)
    context_group_slot_mapping = pl.create_tensor([3, 512], dtype=pl.INT64)
    query_group_position_ids = pl.create_tensor([80], dtype=pl.INT32)
    query_group_slot_mapping = pl.create_tensor([3, 80], dtype=pl.INT64)
    context_group_freqs_cos = pl.create_tensor([512, 64], dtype=pl.BF16)
    context_group_freqs_sin = pl.create_tensor([512, 64], dtype=pl.BF16)
    query_freqs_cos = pl.create_tensor([20, 64], dtype=pl.BF16)
    query_freqs_sin = pl.create_tensor([20, 64], dtype=pl.BF16)
    query_group_freqs_cos = pl.create_tensor([80, 64], dtype=pl.BF16)
    query_group_freqs_sin = pl.create_tensor([80, 64], dtype=pl.BF16)
    select_drafter_metadata(
        request_state,
        context_group_position_ids_bank,
        context_group_slot_mapping_bank,
        query_group_position_ids_bank,
        query_group_slot_mapping_bank,
        context_group_freqs_cos_bank,
        context_group_freqs_sin_bank,
        query_freqs_cos_bank,
        query_freqs_sin_bank,
        query_group_freqs_cos_bank,
        query_group_freqs_sin_bank,
        num_sampled,
        last_sampled,
        next_prefill_tokens,
        anchor_positions,
        context_group_position_ids,
        context_group_slot_mapping,
        query_group_position_ids,
        query_group_slot_mapping,
        context_group_freqs_cos,
        context_group_freqs_sin,
        query_freqs_cos,
        query_freqs_sin,
        query_group_freqs_cos,
        query_group_freqs_sin,
        my_rank,
        prior_cycle_gate,
    )
    computed_head_hidden, head_ready_tid, cleanup_tid = dspark_drafter(
        target_hidden,
        main_proj_weight,
        main_norm_weight,
        num_sampled,
        last_sampled,
        next_prefill_tokens,
        embedding_weight,
        context_group_position_ids,
        context_group_slot_mapping,
        anchor_positions,
        block_tables,
        query_group_position_ids,
        query_group_slot_mapping,
        context_group_freqs_cos,
        context_group_freqs_sin,
        query_freqs_cos,
        query_freqs_sin,
        query_group_freqs_cos,
        query_group_freqs_sin,
        hc_attn_fn,
        hc_attn_scale,
        hc_attn_base,
        attn_norm_w,
        wq_a,
        wq_b,
        wq_b_scale,
        wkv,
        gamma_cq,
        gamma_ckv,
        kv_caches,
        attn_sink,
        wo_a,
        wo_b,
        wo_b_scale,
        hc_ffn_fn,
        hc_ffn_scale,
        hc_ffn_base,
        ffn_norm_w,
        gate_w,
        gate_bias,
        tid2eid,
        routed_w1,
        routed_w1_scale,
        routed_w3,
        routed_w3_scale,
        routed_w2,
        routed_w2_scale,
        shared_w1,
        shared_w1_scale,
        shared_w3,
        shared_w3_scale,
        shared_w2,
        shared_w2_scale,
        hc_head_fn,
        hc_head_scale,
        hc_head_base,
        initial_hidden,
        intermediate_hidden,
        head_hidden,
        hidden_gather_window,
        hidden_gather_signal,
        attention_window,
        attention_signal,
        o_window,
        o_signal,
        recv_meta,
        recv_x,
        recv_aux,
        recv_route,
        arrived,
        data_arrived,
        routed_y_buf,
        combine_arrived,
        group_base,
        dsa_cp_rank,
        my_rank,
        prior_cycle_gate,
    )
    return (computed_head_hidden, head_ready_tid, cleanup_tid)
